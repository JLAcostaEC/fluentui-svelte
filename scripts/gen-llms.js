import fs from 'node:fs';
import path from 'node:path';

/**
 * Keeps the agent-facing docs in sync with the components.
 *
 * 1. Rewrites the component index of the agent skill (`skills/fluentui-svelte/SKILL.md`),
 *    between the `components:start` and `components:end` markers, from each `docs/meta.ts`
 *    and the components `src/lib/index.ts` exports from its folder. Also writes the version of
 *    the package into the skill, so `changeset:version` runs this script too.
 * 2. Puts the note that points to the global guide under the title of every `docs/llms.md`.
 * 3. Writes `src/site/utils/llms-index.js` (git-ignored): the slug, title, description and status of each
 *    component for the Markdown endpoints of the site. It stands in for `components-index.js`, whose
 *    `META` objects import icon components that the endpoints do not need.
 *
 * `--check` writes nothing and exits with 1 when a committed file is out of date.
 */

export const SITE_URL = 'https://fluentui-svelte.dev';
export const SKILL_PATH = 'skills/fluentui-svelte/SKILL.md';
export const GLOBAL_NOTE =
	`> Part of fluentui-svelte. Read the global guide first (setup, rules and pitfalls): ` +
	`${SITE_URL}/docs/llms.md, also shipped as node_modules/fluentui-svelte/${SKILL_PATH}`;

const LIB_PATH = 'src/lib/components';
const LIB_INDEX_PATH = 'src/lib/index.ts';
const INDEX_PATH = 'src/site/utils/llms-index.js';
const START = '<!-- components:start -->';
const END = '<!-- components:end -->';
const VERSION = /(Written for fluentui-svelte )`[^`]*`/;
// Statuses that warn the API may still change. `New` and `AI` say nothing about stability.
const UNSTABLE = new Set(['Beta', 'Experimental', 'Prototype', 'WIP', 'Empty']);

/** @param {string} source @param {string} key */
const field = (source, key) => source.match(new RegExp(`^\\s*${key}:\\s*(['"\`])(.*?)\\1`, 'm'))?.[2] ?? '';

/** The version of the package, from `package.json`. */
export const packageVersion = () => JSON.parse(fs.readFileSync('package.json', 'utf-8')).version;

/** The Svelte components the package exports, grouped by component folder, in the order of `src/lib/index.ts`. */
function exportsByFolder() {
	const source = fs.readFileSync(LIB_INDEX_PATH, 'utf-8');
	/** @type {Map<string, string[]>} */
	const byFolder = new Map();
	for (const [, name, folder] of source.matchAll(
		/export \{ default as (\w+) \} from '\.\/components\/([^/]+)\/[^']+\.svelte'/g
	)) {
		byFolder.set(folder, [...(byFolder.get(folder) ?? []), name]);
	}
	return byFolder;
}

/** Every documented component, sorted by folder. */
export function readComponents() {
	const folders = fs
		.readdirSync(LIB_PATH)
		.filter((folder) => fs.existsSync(path.join(LIB_PATH, folder, 'docs', 'meta.ts')))
		.sort();
	const exports = exportsByFolder();

	return folders.map((folder) => {
		const meta = fs.readFileSync(path.join(LIB_PATH, folder, 'docs', 'meta.ts'), 'utf-8');
		const llmsPath = path.join(LIB_PATH, folder, 'docs', 'llms.md');

		return {
			folder,
			slug: field(meta, 'slug') || folder,
			title: field(meta, 'title'),
			description: field(meta, 'description'),
			status: field(meta, 'status'),
			exports: exports.get(folder) ?? [],
			llmsPath: fs.existsSync(llmsPath) ? llmsPath : null
		};
	});
}

/** @param {ReturnType<typeof readComponents>} components */
export function componentIndex(components) {
	const lines = components.map(({ folder, title, description, status, exports }) => {
		const names = exports.length ? exports.map((name) => `\`${name}\``).join(', ') : `**${title}**`;
		const badge = UNSTABLE.has(status) ? ` _(${status})_` : '';
		return `- \`${folder}\`: ${names}${badge}. ${description}`;
	});
	return `${START}\n\n${lines.join('\n')}\n\n${END}`;
}

/**
 * @param {string} skill
 * @param {ReturnType<typeof readComponents>} components
 * @param {string} version
 */
export function updateSkill(skill, components, version) {
	const start = skill.indexOf(START);
	const end = skill.indexOf(END);
	if (start === -1 || end === -1) throw new Error(`${SKILL_PATH} lacks the ${START} / ${END} markers.`);
	if (!VERSION.test(skill)) throw new Error(`${SKILL_PATH} lacks the "Written for fluentui-svelte \`x.y.z\`" line.`);

	const indexed = skill.slice(0, start) + componentIndex(components) + skill.slice(end + END.length);
	return indexed.replace(VERSION, `$1\`${version}\``);
}

/** @param {ReturnType<typeof readComponents>} components */
export function siteIndex(components) {
	const entries = components.map(({ slug, title, description, status }) => ({ slug, title, description, status }));
	return (
		`// AUTO-GENERATED by scripts/gen-llms.js — do not edit by hand.\n` +
		`// Run \`pnpm urls\` to regenerate.\n\n` +
		`/** @type {{ slug: string; title: string; description: string; status: string }[]} */\n` +
		`export default ${JSON.stringify(entries, null, '\t')};\n`
	);
}

/** @param {string} llms */
export function updateLlms(llms) {
	const lines = llms.split('\n');
	const note = lines.findIndex((line) => line.startsWith('> Part of fluentui-svelte.'));
	if (note !== -1) {
		lines[note] = GLOBAL_NOTE;
		return lines.join('\n');
	}
	const title = lines.findIndex((line) => line.startsWith('# '));
	lines.splice(title + 1, 0, '', GLOBAL_NOTE);
	return lines.join('\n');
}

function run() {
	const check = process.argv.includes('--check');
	const components = readComponents();
	/** @type {[string, string][]} */
	const outputs = [];

	const skill = fs.readFileSync(SKILL_PATH, 'utf-8');
	outputs.push([SKILL_PATH, updateSkill(skill, components, packageVersion())]);

	for (const { llmsPath, folder } of components) {
		if (llmsPath === null) {
			console.error(`${folder} has docs but no docs/llms.md.`);
			process.exitCode = 1;
			continue;
		}
		outputs.push([llmsPath, updateLlms(fs.readFileSync(llmsPath, 'utf-8'))]);
	}

	const stale = outputs.filter(([file, content]) => fs.readFileSync(file, 'utf-8') !== content);
	if (check) {
		for (const [file] of stale) console.error(`${file} is out of date. Run \`pnpm urls\`.`);
		if (stale.length) process.exitCode = 1;
		return;
	}
	for (const [file, content] of stale) fs.writeFileSync(file, content, 'utf-8');
	console.info(stale.length ? `Updated ${stale.length} agent doc(s).` : 'Agent docs are up to date.');

	const index = siteIndex(components);
	if (!fs.existsSync(INDEX_PATH) || fs.readFileSync(INDEX_PATH, 'utf-8') !== index) {
		fs.writeFileSync(INDEX_PATH, index, 'utf-8');
		console.info(`Wrote ${components.length} component(s) to ${INDEX_PATH}.`);
	}
}

if (process.argv[1] && path.resolve(process.argv[1]) === path.resolve(import.meta.filename)) run();
