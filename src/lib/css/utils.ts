export const pickColorByWord = (word?: string): string => {
	const random = () => colors[Math.floor(Math.random() * colors.length)].toLowerCase();

	if (!word) return random();

	for (const char of word) {
		const matches = colors.filter((c) => c.toLowerCase().startsWith(char.toLowerCase()));
		if (matches.length > 0) return matches[Math.floor(Math.random() * matches.length)].toLowerCase();
	}

	return random();
};
